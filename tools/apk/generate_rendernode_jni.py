#!/usr/bin/env python3
"""Check the original RenderNode JNI contract and generate a selective host bootstrap."""
import argparse
import hashlib
import json
from pathlib import Path
import re

PROFILE = (
    'nCreate', 'nGetNativeFinalizer', 'nSetClipToBounds', 'nGetClipToBounds',
    'nGetUniqueId', 'nSetLeftTopRightBottom', 'nGetLeft', 'nGetTop', 'nGetRight',
    'nGetBottom', 'nGetWidth', 'nGetHeight', 'nSetAlpha', 'nGetAlpha',
    'nDiscardDisplayList', 'nIsValid',
)
TYPES = {'void':'V','boolean':'Z','byte':'B','char':'C','short':'S','int':'I',
         'long':'J','float':'F','double':'D','String':'Ljava/lang/String;',
         'WeakReference':'Ljava/lang/ref/WeakReference;'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sources', type=Path, required=True)
    parser.add_argument('--aosp-cache', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    java_manifest = json.loads((root/'runtime/aosp/framework-study.json').read_text())
    native_manifest = json.loads((root/'runtime/aosp/hwui-sources.json').read_text())
    hwui = next(c for c in native_manifest['components'] if c['name']=='hwui')
    if '/'+java_manifest['revision']+'/' not in hwui['archive_url']:
        raise SystemExit('RenderNode Java/C++ source revisions differ')
    java_name = 'graphics/java/android/graphics/RenderNode.java'
    java_item = next(f for f in java_manifest['files'] if f['path']==java_name)
    originals = [
        (args.aosp_cache/java_name, java_item['sha256']),
        (args.sources/'hwui/jni/android_graphics_RenderNode.cpp', hwui['files']['jni/android_graphics_RenderNode.cpp']['sha256']),
        (args.sources/'hwui/jni/graphics_jni_helpers.h', hwui['files']['jni/graphics_jni_helpers.h']['sha256']),
    ]
    for path, expected in originals:
        if hashlib.sha256(path.read_bytes()).hexdigest()!=expected:
            raise SystemExit('Original source modified: '+str(path))
    java = originals[0][0].read_text()
    cpp = originals[1][0].read_text()
    # This parser deliberately accepts only the pinned source's declaration form.
    java = re.sub(r'/\*.*?\*/|//[^\n]*', '', java, flags=re.S)
    pattern = r'((?:@\w+(?:\([^)]*\))?\s*)*)(?:private|public|protected)\s+static\s+native\s+(\w+)\s+(\w+)\s*\(([^)]*)\)\s*;'
    methods = {}
    for annotations, result, name, arguments in re.findall(pattern, java):
        params = []
        arguments = re.sub(r'<[^>]+>', '', arguments)
        for argument in arguments.split(',') if arguments.strip() else []:
            match = re.fullmatch(r'\s*(\w+)\s+\w+\s*', argument)
            if not match or match[1] not in TYPES:
                raise SystemExit('Unrecognized original parameter: '+argument)
            params.append(TYPES[match[1]])
        if result not in TYPES or name in methods:
            raise SystemExit('Unrecognized or duplicate original declaration: '+name)
        descriptor = '('+''.join(params)+')'+TYPES[result]
        critical = '@CriticalNative' in annotations
        if critical and any(c in descriptor for c in ('L','[')):
            raise SystemExit('Critical method contains a reference: '+name)
        methods[name] = {'name':name,'descriptor':descriptor,'critical':critical}
    table = re.search(r'static const JNINativeMethod gMethods\[\]\s*=\s*\{(.*?)\n\};', cpp, re.S)
    if not table:
        raise SystemExit('Original JNI table not found')
    entries = re.findall(r'\{\s*"(\w+)"\s*,\s*"([^"]+)"\s*,\s*\(void\*\)\s*(\w+)\s*\}', table[1])
    if len(entries)!=len(methods) or {e[0] for e in entries}!=set(methods):
        raise SystemExit('Original Java/C++ method sets differ or parser missed entries')
    for name, descriptor, function in entries:
        item = methods[name]
        if item['descriptor']!=descriptor:
            raise SystemExit('Original Java/C++ descriptor mismatch: '+name)
        declaration = re.search(r'\b'+re.escape(function)+r'\s*\(\s*(CRITICAL_JNI_PARAMS(?:_COMMA)?\b)?', cpp)
        if not declaration or bool(declaration[1])!=item['critical']:
            raise SystemExit('Original Java/C++ calling convention mismatch: '+name)
        item.update(cpp_function=function, selected=name in PROFILE)
    if not set(PROFILE)<=set(methods):
        raise SystemExit('Construction profile includes an absent method')
    lines = ['// Generated by tools/apk/generate_rendernode_jni.py; do not edit.',
             '// Selective construction/property profile; other methods remain unregistered.',
             '#include "critical-host-adapter.h"',
             '#include "jni/android_graphics_RenderNode.cpp"', '',
             'using archtv::aosp::CriticalHostAdapter;',
             'static const JNINativeMethod hostMethods[] = {']
    for name in PROFILE:
        item = methods[name]
        target = '&android::'+item['cpp_function']
        if item['critical']:
            target = 'CriticalHostAdapter<'+target+'>::call'
        lines.append('    {"'+name+'", "'+item['descriptor']+'", (void*)'+target+'},')
    lines += ['};', '', 'extern "C" JNIEXPORT jint JNICALL JNI_OnLoad(JavaVM* vm, void*) {',
              '    JNIEnv* env = nullptr;',
              '    if (vm->GetEnv(reinterpret_cast<void**>(&env), JNI_VERSION_1_6) != JNI_OK) return JNI_ERR;',
              '    jclass type = env->FindClass("android/graphics/RenderNode");',
              '    if (!type) return JNI_ERR;',
              '    jint result = env->RegisterNatives(type, hostMethods, sizeof(hostMethods)/sizeof(hostMethods[0]));',
              '    env->DeleteLocalRef(type);',
              '    return result == JNI_OK ? JNI_VERSION_1_6 : JNI_ERR;', '}', '']
    generated = '\n'.join(lines)
    metadata = json.dumps({'revision':java_manifest['revision'],
        'original_sources_sha256':{str(path.name):expected for path,expected in originals},
        'original_contract_methods':len(methods),'selected_methods':len(PROFILE),
        'selected_critical_methods':sum(methods[n]['critical'] for n in PROFILE),
        'profile':'construction-properties', 'methods':[methods[n] for n in sorted(methods)],
        'scope':'Source-verified JNI registration generation only. Position-listener and animator callbacks excluded. No compilation, linkage or original RenderNode execution claim.'},indent=2)+'\n'
    outputs = [(args.output, generated),(args.output.with_suffix('.json'), metadata)]
    for path, content in outputs:
        if args.check:
            if path.read_text()!=content:
                raise SystemExit('Generated adapter stale: '+str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(json.dumps({'original_contract_methods':len(methods),'selected_methods':len(PROFILE)}))


if __name__=='__main__':
    main()
