#!/usr/bin/env python3
"""Generate explicit Linux hooks for a pinned original abstract Context; unsupported hooks throw."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('--aosp-build', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
framework = args.aosp_build/'framework.jar'
proof = json.loads((args.aosp_build/'provenance.json').read_text())
assert hashlib.sha256(framework.read_bytes()).hexdigest() == proof['framework_jar_sha256']
text = subprocess.check_output(['/usr/lib/jvm/java-17-openjdk/bin/javap', '-classpath', str(framework),
                                '-protected', 'android.content.Context'], text=True)

def parameters(text):
    result, start, depth = [], 0, 0
    for index, char in enumerate(text):
        if char == '<': depth += 1
        elif char == '>': depth -= 1
        elif char == ',' and depth == 0:
            result.append(text[start:index].strip()); start = index+1
    if text.strip(): result.append(text[start:].strip())
    return result

lines = ['package org.archtv.apkruntime;', '',
    '// Generated by tools/apk/generate_linux_context.py from original Context declarations.',
    '// Linux service boundary: supported hooks delegate to real host state; other hooks fail explicitly.',
    'public class LinuxContext extends android.content.Context {']
count = supported = 0
for line in text.splitlines():
    line = line.strip().replace('$', '.')
    if not line.endswith(';') or ' abstract ' not in line: continue
    access, declaration = line.split(' abstract ', 1)
    declaration = declaration.split(' throws ', 1)[0].removesuffix(';')
    head, tail = declaration.split('(', 1)
    result_type, name = head.rsplit(' ', 1)
    types = parameters(tail.removesuffix(')'))
    arguments = ', '.join(kind+' p'+str(index) for index, kind in enumerate(types))
    body = None
    if not types:
        body = {
            'getResources': 'return AppEnvironment.current().resources.platformResources();',
            'getAssets': 'return AppEnvironment.current().resources.platformAssets();',
            'getApplicationInfo': 'return AppEnvironment.current().applicationInfo();',
            'getPackageName': 'return AppEnvironment.current().applicationInfo().packageName;',
            'getDisplayId': 'Integer id = AppEnvironment.current().virtualDisplayId; if (id == null) throw new UnsupportedOperationException("No visual display attached to this Linux context"); return id;',
            'getMainLooper': 'return android.os.Looper.getMainLooper();',
            'getClassLoader': 'return getClass().getClassLoader();',
            'getApplicationContext': 'return AppEnvironment.current().applicationContext;',
        }.get(name)
    if name == 'getSharedPreferences' and types == ['java.lang.String', 'int']:
        body = 'if (p1 != MODE_PRIVATE) throw new UnsupportedOperationException("Only MODE_PRIVATE is supported"); return AppEnvironment.current().preferences(p0);'
    if body is None:
        body = 'throw new UnsupportedOperationException("Unsupported Linux context API: '+name+'");'
    else: supported += 1
    lines += ['    @Override '+access+' '+result_type+' '+name+'('+arguments+') {', '        '+body, '    }']
    count += 1
lines += ['}', '']
output = '\n'.join(lines)
if args.check:
    assert args.output.read_text() == output, 'Linux context hooks differ from pinned abstract API'
else:
    with args.output.open('x') as stream: stream.write(output)
print(json.dumps({'abstract_hooks':count, 'supported_hooks':supported, 'unsupported_hooks':count-supported}))
